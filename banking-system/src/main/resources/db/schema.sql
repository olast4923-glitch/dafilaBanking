-- CSE202 Banking System - schema
-- Written in portable SQL so the same file runs on Supabase PostgreSQL and H2.
-- accounts uses single-table inheritance: account_type is the discriminator
-- that JdbcAccountDAO maps back to SavingsAccount / InvestmentAccount / ChequeAccount.

CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(100) NOT NULL,
  surname VARCHAR(100) NOT NULL,
  address VARCHAR(255),
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  employed BOOLEAN NOT NULL DEFAULT FALSE,
  employer_name VARCHAR(150),
  employer_address VARCHAR(255),
  created_at TIMESTAMP NOT NULL
);

CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_number VARCHAR(30) NOT NULL UNIQUE,
  customer_id BIGINT NOT NULL,
  account_type VARCHAR(20) NOT NULL,
  balance NUMERIC(14,2) NOT NULL,
  branch VARCHAR(100) NOT NULL,
  interest_rate NUMERIC(10,6) NOT NULL DEFAULT 0,
  employer_name VARCHAR(150),
  employer_address VARCHAR(255),
  opened_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_number VARCHAR(30) NOT NULL,
  txn_type VARCHAR(20) NOT NULL,
  amount NUMERIC(14,2) NOT NULL,
  balance_after NUMERIC(14,2) NOT NULL,
  note VARCHAR(255),
  occurred_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_accounts_customer ON accounts(customer_id);
CREATE INDEX idx_txn_account ON transactions(account_number);
